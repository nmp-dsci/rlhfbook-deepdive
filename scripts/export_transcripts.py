#!/usr/bin/env python3
"""Export Nathan Lambert's transcripts from transcript-rag-agent into this repo.

transcript-rag-agent is the single source of truth: this script only reads its Chroma store and
never fetches anything. It writes a local, gitignored read copy (sources/transcripts/<id>.md) and
the committed catalogue (sources/catalog.json), which holds facts and hashes but no transcript text.

The store is read through chroma.sqlite3 opened with mode=ro, as rotation-tracker does: it cannot
write, needs no chromadb dependency, and is safe while the transcript server has the store open.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sqlite3
from contextlib import closing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TRANSCRIPTS = ROOT / "sources" / "transcripts"
CATALOG = ROOT / "sources" / "catalog.json"
COURSE_MAP = ROOT / "sources" / "course-map.json"
DEFAULT_STORE = ROOT.parent / "transcript-rag-agent" / ".yt-agent" / "chroma"

#: The store holds both forms: Supadata returns the handle for some videos and the id for others.
LAMBERT_CHANNEL_IDS = {"UCayQjCHzSnqPszcHNMmfkSg", "@natolambert"}
COLLECTION = "raw_transcripts"
BLOCK_SECONDS = 30.0
KEPT_METADATA = ("title", "channel_id", "channel_name", "upload_date", "fetched_at", "provider")

RECORDS_SQL = """
SELECT e.embedding_id, m.key, m.string_value, m.int_value, m.float_value
FROM embeddings e JOIN embedding_metadata m ON m.id = e.id
WHERE e.segment_id = (
    SELECT s.id FROM segments s JOIN collections c ON c.id = s.collection
    WHERE c.name = ? AND s.scope = 'METADATA')
"""


def read_records(store: Path) -> dict[str, dict[str, Any]]:
    """Every raw transcript in the store as {video_id: metadata + 'document'}."""
    uri = f"{(store / 'chroma.sqlite3').as_uri()}?mode=ro"
    records: dict[str, dict[str, Any]] = {}
    with closing(sqlite3.connect(uri, uri=True)) as con:
        for embedding_id, key, string_value, int_value, float_value in con.execute(
            RECORDS_SQL, (COLLECTION,)
        ):
            value = next((v for v in (string_value, int_value, float_value) if v is not None), None)
            records.setdefault(embedding_id, {})[key] = value
    by_video = {}
    for record in records.values():
        if "video_id" in record and "chroma:document" in record:
            record["document"] = record.pop("chroma:document")
            by_video[str(record["video_id"])] = record
    return by_video


def course_roles(course_map: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """{video_id: {role, course_id, chapters}} for every video the course page links."""
    roles: dict[str, dict[str, Any]] = {}
    for talk in course_map["talks"]:
        roles[talk["video_id"]] = {"role": "talk", "chapters": talk["chapters"]}
    for entry in course_map["course"]:
        roles[entry["video_id"]] = {
            "role": entry["kind"],
            "course_id": entry["id"],
            "chapters": entry["chapters"],
        }
    return roles


def select_lambert(
    records: dict[str, dict[str, Any]], roles: dict[str, dict[str, Any]]
) -> dict[str, dict[str, Any]]:
    """Lambert's own channel, plus whatever his course page links on other channels."""
    return {
        video_id: record
        for video_id, record in records.items()
        if record.get("channel_id") in LAMBERT_CHANNEL_IDS or video_id in roles
    }


def timestamp(seconds: float) -> str:
    whole = int(seconds)
    return f"{whole // 3600:02d}:{whole % 3600 // 60:02d}:{whole % 60:02d}"


def blocks(segments: list[dict[str, Any]]) -> list[tuple[float, str]]:
    """Group caption segments into (start, text) blocks of about BLOCK_SECONDS each."""
    grouped: list[tuple[float, str]] = []
    start: float | None = None
    words: list[str] = []
    for segment in segments:
        text = " ".join(str(segment.get("text") or "").split())
        if not text:
            continue
        at = float(segment.get("start_seconds") or 0.0)
        if start is None:
            start = at
        elif at - start >= BLOCK_SECONDS:
            grouped.append((start, " ".join(words)))
            start, words = at, []
        words.append(text)
    if start is not None:
        grouped.append((start, " ".join(words)))
    return grouped


def render(video_id: str, record: dict[str, Any], grouped: list[tuple[float, str]]) -> str:
    header = [
        f"# {record.get('title') or video_id}",
        "",
        f"- url: https://www.youtube.com/watch?v={video_id}",
        f"- channel: {record.get('channel_name') or 'unknown'}",
        f"- uploaded: {str(record.get('upload_date') or '')[:10]}",
        f"- fetched: {record.get('fetched_at') or ''} ({record.get('provider') or 'unknown'})",
        "- generated by scripts/export_transcripts.py; auto-captions, no speaker labels; "
        "do not edit, do not commit",
        "",
    ]
    return "\n".join(header + [f"[{timestamp(at)}] {text}\n" for at, text in grouped])


def entry_for(
    video_id: str, record: dict[str, Any], roles: dict[str, dict[str, Any]]
) -> tuple[dict[str, Any], str]:
    """The catalogue entry for one video, and its rendered transcript."""
    segments = json.loads(record["document"])["segments"]
    text = render(video_id, record, blocks(segments))
    entry: dict[str, Any] = {"video_id": video_id}
    entry.update({key: record.get(key) for key in KEPT_METADATA})
    entry.update(
        duration_seconds=float(record.get("duration_seconds") or 0),
        url=f"https://www.youtube.com/watch?v={video_id}",
        word_count=sum(len(str(s.get("text") or "").split()) for s in segments),
        transcript_sha256=hashlib.sha256(text.encode()).hexdigest(),
        **roles.get(video_id, {"role": "channel", "chapters": []}),
    )
    return entry, text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--store", type=Path, default=Path(os.environ.get("YT_AGENT_CHROMA", DEFAULT_STORE))
    )
    args = parser.parse_args()

    roles = course_roles(json.loads(COURSE_MAP.read_text()))
    records = read_records(args.store)
    wanted = select_lambert(records, roles)

    TRANSCRIPTS.mkdir(parents=True, exist_ok=True)
    entries = []
    for video_id, record in wanted.items():
        entry, text = entry_for(video_id, record, roles)
        (TRANSCRIPTS / f"{video_id}.md").write_text(text)
        entries.append(entry)
    entries.sort(key=lambda e: (e["upload_date"] or "", e["video_id"]), reverse=True)
    CATALOG.write_text(json.dumps(entries, indent=2, ensure_ascii=False) + "\n")

    print(f"exported {len(entries)} transcripts to {TRANSCRIPTS.relative_to(ROOT)}/")
    missing = sorted(set(roles) - set(wanted))
    if missing:
        print(f"MISSING from the store, linked by the course page: {', '.join(missing)}")
        print("Collect them in transcript-rag-agent (see AGENTS.md), then re-run this.")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
